#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Rebuild chibi-blue at exactly 30 palette entries (index 0 transparent + 29 colors).

The 16-color skin is backed up at build/skins/chibi-blue-16c/.  This script reuses
the already verified source windows/frame counts from chibi_build_16c.json instead
of re-running the window search, so the loop closure stays identical.  Only
pretooluse.gif needs one fewer frame (11 -> 10) to fit the new 64000-byte cap at
30 colors.

Usage: python tools/rebuild_30color.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build_pet_skin as bp  # noqa: E402

OUT = ROOT / "build" / "skins" / "chibi-blue"
WORK = ROOT / "build" / "skins" / "_work"
BASE_JSON = WORK / "chibi_build_16c.json"

TARGET_COLORS = 30
MAX_BYTES = 64000
MAX_GAP = 8.0
MIN_FRAMES = 8
MAX_FRAMES = 12
SPEEDS = [("slow", 150), ("normal", 120), ("fast", 90)]
LABELS = {
    "Idle": "待机",
    "UserPromptSubmit": "元气挥手",
    "PreToolUse": "写代码",
    "PostToolUse": "轻快记录",
    "PermissionRequest": "期待开饭",
    "Error": "垂头叹气",
    "Stop": "雀跃庆祝",
    "SessionStart": "伸懒腰",
    "SubagentStart": "三球抛接",
    "SubagentStop": "拆礼物",
    "PreCompact": "深度思考",
    "PostCompact": "清点归档",
    "Sleeping": "睡觉",
}


def baseline() -> dict[str, dict]:
    rows = json.loads(BASE_JSON.read_text(encoding="utf-8"))
    return {r["file"]: r for r in rows if r["speed"] == "normal"}


def build_action(base: dict) -> dict:
    """Re-use the verified window, try the base frame count then decrease to 8."""
    src_name = base["source"][:-5] if base["source"].endswith(".webm") else base["source"]
    arr, _w, _h = bp.decode_webm(bp.ensure_webm(src_name))
    start = int(round(float(base["window_start"]) * bp.FPS))
    win = int(round(float(base["window_sec"]) * bp.FPS))
    nf0 = int(base["frames"])
    if not (MIN_FRAMES <= nf0 <= MAX_FRAMES):
        raise RuntimeError("%s 基线帧数 %d 不在 %d-%d" % (base["file"], nf0, MIN_FRAMES, MAX_FRAMES))

    for nf in range(nf0, MIN_FRAMES - 1, -1):
        idx = bp.window_indices(start, win, nf)
        if len(idx) != nf:
            continue
        frames, _tw, _th = bp.prepare(bp.render_frames(arr, idx))
        trial = bp.encode(frames, TARGET_COLORS, Image.Quantize.MEDIANCUT, 120)
        gap = bp._bytes_gap(trial)
        if len(trial) > MAX_BYTES or gap >= MAX_GAP:
            continue
        data = {}
        for speed, ms in SPEEDS:
            data[speed] = bp.encode(frames, TARGET_COLORS, Image.Quantize.MEDIANCUT, ms)
        return {
            "event": base["event"],
            "file": base["file"],
            "source": src_name + ".webm",
            "note": base["note"],
            "frames": nf,
            "base_frames": nf0,
            "colors": TARGET_COLORS,
            "start": start,
            "win": win,
            "gap": gap,
            "data": data,
        }
    raise RuntimeError("%s 在 %d 色、<=%d B、gap<%.1f 下找不到 8-12 帧方案"
                       % (base["file"], TARGET_COLORS, MAX_BYTES, MAX_GAP))


def write_manifest() -> None:
    order = []
    for ev, *_ in bp.EVENT_SPECS:
        if ev not in order:
            order.append(ev)
    lines = [
        "-- Generated by tools/rebuild_30color.py",
        "-- 皮肤 ID: chibi-blue（蓝发少女，30色），素材来自 PC2005-cloud/dsh-pet (MIT)",
        "return {",
        '  id = "chibi-blue",',
        '  name = "蓝发少女",',
        '  name_en = "Blue-Haired Girl",',
        "  labels = {",
    ]
    for ev in order:
        lines.append('    ["%s"] = "%s",' % (ev, LABELS[ev]))
    lines += [
        "  },",
        "  speeds = { slow = 150, normal = 120, fast = 90 },",
        '  default_speed = "normal",',
        "  events = {",
    ]
    for ev in order:
        files = [s[1] for s in bp.EVENT_SPECS if s[0] == ev]
        lines.append('    ["%s"] = { %s },' % (ev, ", ".join('"%s"' % f for f in files)))
    lines += ["  },", "  weather = {},", "}", ""]
    (OUT / "manifest.lua").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_preview(records: list[dict]) -> None:
    cols, rows = 4, 4
    cell_w, cell_h, pad = 184, 204, 8
    sheet = Image.new("RGBA", (cols * cell_w, rows * cell_h), (32, 34, 42, 255))
    dr = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.truetype(r"C:\Windows\Fonts\msyh.ttc", 11)
    except OSError:
        font = ImageFont.load_default()

    normal = [r for r in records if r["speed"] == "normal"]
    for i, r in enumerate(normal):
        cx, cy = (i % cols) * cell_w, (i // cols) * cell_h
        board = Image.new("RGBA", (bp.CANVAS, bp.CANVAS), (255, 255, 255, 255))
        bd = ImageDraw.Draw(board)
        step = 10
        for y in range(0, bp.CANVAS, step):
            for x in range(0, bp.CANVAS, step):
                if (x // step + y // step) % 2:
                    bd.rectangle([x, y, x + step - 1, y + step - 1], fill=(205, 205, 215, 255))
        im = Image.open(r["path"])
        im.seek(0)
        board.alpha_composite(im.convert("RGBA"))
        sheet.alpha_composite(board, (cx + pad, cy + 34))
        dr.text((cx + pad, cy + 5), "%s  %df %dc" % (r["file"][:-4], r["frames"], r["colors"]),
                fill=(235, 235, 245, 255), font=font)
        dr.text((cx + pad, cy + 20), "%.1f KB" % (r["bytes"] / 1024.0),
                fill=(170, 185, 210, 255), font=font)
    sheet.convert("RGB").save(OUT / "preview.png", optimize=True)


