def main() -> int:
    if not BASE_JSON.is_file():
        raise SystemExit("找不到基线: %s" % BASE_JSON)
    base = baseline()
    built = []
    for ev, out_name, webm_name, _preview, note in bp.EVENT_SPECS:
        if out_name not in base:
            raise SystemExit("基线缺少 %s" % out_name)
        rec = build_action(base[out_name])
        built.append(rec)
        print("%-24s %2d 帧 (%d) %2d 色 %6d B gap %.2f"
              % (out_name, rec["frames"], rec["base_frames"], TARGET_COLORS,
                 len(rec["data"]["normal"]), rec["gap"]), flush=True)

    for s, _ in SPEEDS:
        d = OUT / s
        d.mkdir(parents=True, exist_ok=True)
        for old in d.glob("*.gif"):
            old.unlink()
    for old in ("report.md", "report-loop.md", "report-12frame.md"):
        p = OUT / old
        if p.is_file():
            p.unlink()

    records = []
    for rec in built:
        for speed, ms in SPEEDS:
            path = OUT / speed / rec["file"]
            path.write_bytes(rec["data"][speed])
            v = bp.verify_gif(path, rec["event"], rec["frames"], ms)
            gap = bp.gif_loop_gap(path)
            im = Image.open(path)
            palette = len(im.getpalette()) // 3
            used = len(im.getcolors(maxcolors=256) or [])
            v.update({
                "speed": speed,
                "duration": ms,
                "source": rec["source"],
                "note": rec["note"],
                "window_start": rec["start"] / bp.FPS,
                "window_sec": rec["win"] / bp.FPS,
                "gap": gap,
                "palette": palette,
                "used_colors": used,
                "base_frames": rec["base_frames"],
                "loop_ok": gap < MAX_GAP,
            })
            if used != TARGET_COLORS:
                raise RuntimeError("%s/%s 实际使用 %d 色，期望 %d"
                                   % (speed, rec["file"], used, TARGET_COLORS))
            if not v["ok"]:
                raise RuntimeError("verify 失败: %s/%s %s"
                                   % (speed, rec["file"], v))
            records.append(v)

    write_manifest()
    write_preview(records)
    write_report(records, base)
    (WORK / "chibi_build_30c.json").write_text(
        json.dumps([{k: (str(v) if isinstance(v, Path) else v) for k, v in r.items()}
                    for r in records], ensure_ascii=False, indent=1),
        encoding="utf-8", newline="\n")
    (WORK / "chibi_build.json").write_text(
        (WORK / "chibi_build_30c.json").read_text(encoding="utf-8"),
        encoding="utf-8", newline="\n")

    total = sum(r["bytes"] for r in records)
    print("\n输出: %s" % OUT)
    print("GIF %d 个，合计 %d B（%.1f KB），最大 %d B"
          % (len(records), total, total / 1024.0, max(r["bytes"] for r in records)))
    print("verify: %d/%d" % (sum(1 for r in records if r["ok"]), len(records)))
    print("gap: mean %.2f / max %.2f" % (sum(r["gap"] for r in records) / len(records),
                                         max(r["gap"] for r in records)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
